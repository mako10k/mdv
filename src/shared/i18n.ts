import { useEffect, useState } from 'react'

export type Locale = 'ja' | 'en'

export function isLocale(value: string): value is Locale {
  return value === 'ja' || value === 'en'
}

function getBootstrapLocale(): Locale {
  const bootstrapLocale = window.mdvDesktop?.settings.getBootstrapSettings().settings.general.locale

  if (bootstrapLocale && isLocale(bootstrapLocale)) {
    return bootstrapLocale
  }

  return navigator.language.toLowerCase().startsWith('ja') ? 'ja' : 'en'
}

export function useLocale() {
  const [locale, setLocale] = useState<Locale>(() => getBootstrapLocale())

  useEffect(() => {
    document.documentElement.lang = locale
  }, [locale])

  useEffect(() => {
    const unsubscribe = window.mdvDesktop?.settings.onSettingsChanged((settings) => {
      if (isLocale(settings.general.locale)) {
        setLocale(settings.general.locale)
      }
    })

    return () => {
      unsubscribe?.()
    }
  }, [])

  return locale
}

